// ------------------------------------------------------------------ schemas

function schemaExpr(f: Field): string {
  const label = lowerLabel(f);
  switch (f.type) {
    case 'text':
    case 'longtext': {
      const max = TEXT_MAX[f.type];
      const tooLong = q(`Keep the ${label} under ${max.toLocaleString('en')} characters`);
      return f.required
        ? `z.string().trim().min(1, ${q(`Enter a ${label}`)}).max(${max}, ${tooLong})`
        : `z.string().trim().max(${max}, ${tooLong}).transform(blankToNull)`;
    }
    case 'int':
      return `${f.required ? 'requiredNumber' : 'optionalNumber'}(WHOLE, ${q('Enter a whole number')})`;
    case 'numeric':
      return `${f.required ? 'requiredNumber' : 'optionalNumber'}(DECIMAL, ${q('Enter a number like 12.5')})`;
    case 'money':
      return `${f.required ? 'requiredNumber' : 'optionalNumber'}(AMOUNT, ${q('Enter an amount like 4500 or 4500.50')})`;
    case 'bool':
      return `z.string().transform((v) => v === 'true')`;
    case 'date':
      return f.required
        ? `z.string().trim().refine(isDay, ${q('Enter a date')})`
        : `z.string().trim().refine((v) => v === '' || isDay(v), ${q('Enter a date')}).transform(blankToNull)`;
  }
}

export function schemasTs(spec: ModuleSpec): string {
  const v = view(spec);
  const types = new Set(v.fields.map((f) => f.type));
  const numeric = v.fields.filter((f) => ['int', 'numeric', 'money'].includes(f.type));
  const needsBlank = v.fields.some(
    (f) => !f.required && (f.type === 'text' || f.type === 'longtext' || f.type === 'date'),
  );
  const helpers: string[] = [];
  if (needsBlank) helpers.push(`const blankToNull = (v: string) => (v === '' ? null : v);`);
  if (types.has('int')) helpers.push(`const WHOLE = /^-?\\d{1,9}$/;`);
  if (types.has('numeric')) helpers.push(`const DECIMAL = /^-?\\d{1,10}(\\.\\d{1,4})?$/;`);
  if (types.has('money'))
    helpers.push(`/** Amounts in major units ("4,500.50"); actions convert to minor units. */
const AMOUNT = /^\\d{1,12}(\\.\\d{1,3})?$/;`);
  if (numeric.some((f) => f.required))
    helpers.push(`/** A number typed into a form (commas allowed). */
function requiredNumber(pattern: RegExp, message: string) {
  return z
    .string()
    .trim()
    .transform((v) => v.replace(/,/g, ''))
    .refine((v) => pattern.test(v), message)
    .transform(Number);
}`);
  if (numeric.some((f) => !f.required))
    helpers.push(`/** An optional number typed into a form: '' becomes null. */
function optionalNumber(pattern: RegExp, message: string) {
  return z
    .string()
    .trim()
    .transform((v) => v.replace(/,/g, ''))
    .refine((v) => v === '' || pattern.test(v), message)
    .transform((v) => (v === '' ? null : Number(v)));
}`);
  if (types.has('date'))
    helpers.push(`/** A real calendar day as YYYY-MM-DD (rejects 2026-02-30). */
export function isDay(v: string): boolean {
  if (!/^\\d{4}-\\d{2}-\\d{2}$/.test(v)) return false;
  const d = new Date(\`\${v}T00:00:00Z\`);
  return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === v;
}`);

  return `import { z } from 'zod';

${helpers.join('\n\n')}

/** A ${v.n.singularLower} as typed into a form: every field is a string. */
export const ${v.id.schema} = z.object({
${v.fields.map((f) => `  ${f.name}: ${schemaExpr(f)},`).join('\n')}
});
export type ${v.id.input} = z.output<typeof ${v.id.schema}>;
`;
}

