function columnSql(f: Field): string {
  const c = f.column;
  const nn = f.required ? ' not null' : '';
  switch (f.type) {
    case 'text':
    case 'longtext': {
      const max = TEXT_MAX[f.type];
      return f.required
        ? `text not null check (char_length(btrim(${c})) between 1 and ${max})`
        : `text check (char_length(${c}) <= ${max})`;
    }
    case 'int':
      return `integer${nn}`;
    case 'numeric':
      return `numeric(14, 4)${nn}`;
    case 'money':
      return `bigint${nn} check (${c} >= 0)`;
    case 'bool':
      return 'boolean not null default false';
    case 'date':
      return `date${nn}`;
  }
}

