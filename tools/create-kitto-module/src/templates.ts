export function appDetailRoute(spec: ModuleSpec): string {
  const v = view(spec);
  return `import type { Metadata } from 'next';
import { getTenantContext } from '@kitto/auth/server';
import { ${v.id.detailPage} } from '@kitto/${v.n.kebab}';

export const metadata: Metadata = { title: ${q(v.n.singularTitle)} };

export default async function Page({
  params,
  searchParams,
}: PageProps<'/t/[tenant]/${v.n.kebab}/[id]'>) {
  const { tenant, id } = await params;
  const ctx = await getTenantContext(tenant);
  return <${v.id.detailPage} ctx={ctx} searchParams={await searchParams} ${v.id.idField}={id} />;
}
`;
}

function e2eFill(f: Field, titleValue: string): string {
  const label =
    f.type === 'money' ? `new RegExp(${q(`^${f.label} \\(`)})` : `${q(f.label)}, { exact: true }`;
  switch (f.type) {
    case 'bool':
      return `  await page.getByLabel(${label}).check();`;
    default:
      return `  await page.getByLabel(${label}).fill(${q(sampleInput(f, titleValue))});`;
  }
}

export function e2eSpec(spec: ModuleSpec): string {
  const v = view(spec);
  const { n, fields, title } = v;
  const first = `${n.singularTitle} one`;
  const renamed = `${n.singularTitle} two`;
  return `import { expect, test } from '@playwright/test';
import { createWorkspace, expectNoSideScroll, uniqueEmail, uniqueSlug } from './helpers';

test('${n.kebab}: add, search, edit and delete', async ({ page }) => {
  const home = await createWorkspace(page, uniqueEmail('owner'), ${q(`${n.title} Co`)}, uniqueSlug('gen'));

  await page
    .getByRole('navigation', { name: 'Main' })
    .getByRole('link', { name: ${q(n.title)}, exact: true })
    .click();
  await expect(page.getByRole('heading', { level: 1, name: ${q(n.title)} })).toBeVisible();
  await expect(page.getByText(${q(`No ${n.lower} yet`)})).toBeVisible();

  await page.getByRole('link', { name: ${q(`New ${n.singularLower}`)} }).click();
${fields.map((f) => e2eFill(f, f === title ? first : `Sample ${lowerLabel(f)}`)).join('\n')}
  await page.getByRole('button', { name: ${q(`Add ${n.singularLower}`)} }).click();
  await expect(page.getByText(${q(`${n.singularTitle} added.`)})).toBeVisible();
  await expect(page.getByRole('heading', { level: 1, name: ${q(first)} })).toBeVisible();
  await expectNoSideScroll(page);
  const detail = page
    .url()
    .replace(/^https?:\\/\\/[^/]+/, '')
    .split('?')[0]!;

  // Edit.
  await page.getByLabel(${q(title.label)}, { exact: true }).fill(${q(renamed)});
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByText(${q(`${n.singularTitle} saved.`)})).toBeVisible();
  await expect(page.getByRole('heading', { level: 1, name: ${q(renamed)} })).toBeVisible();

  // Search.
  await page.goto(\`\${home}/${n.kebab}\`);
  const search = page.getByRole('searchbox', { name: ${q(`Search ${n.lower}`)} });
  await search.fill('two');
  await page.getByRole('button', { name: 'Search' }).click();
  await expect(page.getByRole('rowheader', { name: ${q(renamed)} })).toBeVisible();
  await search.fill('nobody-here');
  await page.getByRole('button', { name: 'Search' }).click();
  await expect(page.getByText(${q(`No matching ${n.lower}`)})).toBeVisible();
  await expectNoSideScroll(page);

  // Delete.
  await page.goto(detail);
  page.once('dialog', (d) => void d.accept());
  await page.getByRole('button', { name: ${q(`Delete ${n.singularLower}`)} }).click();
  await expect(page.getByText(${q(`${n.singularTitle} deleted.`)})).toBeVisible();
  await expect(page).toHaveURL(new RegExp(\`\${home}/${n.kebab}\\\\?notice=deleted$\`));
  expect((await page.goto(detail))?.status()).toBe(404);
});
`;
}
