// ------------------------------------------------------------------- shared

function errorMessage(f: Field): string | null {
  const label = lowerLabel(f);
  switch (f.type) {
    case 'text':
    case 'longtext': {
      const max = TEXT_MAX[f.type].toLocaleString('en');
      return f.required
        ? `Enter a ${label} of up to ${max} characters.`
        : `Keep the ${label} under ${max} characters.`;
    }
    case 'int':
      return `Enter a whole number for ${label}.`;
    case 'numeric':
      return `Enter a number for ${label}, e.g. 12.5.`;
    case 'money':
      return `Enter an amount for ${label}, e.g. 4500 or 4500.50.`;
    case 'date':
      return `Enter a valid date for ${label}.`;
    case 'bool':
      return null;
  }
}

