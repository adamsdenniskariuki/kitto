/**
 * File templates for a generated module. Each mirrors the matching file in
 * packages/customers (the reference CRUD module) so generated code follows the
 * same conventions: tenant_id + composite key, RLS through
 * private.permitted_tenant_ids(), registered permissions, audit, column
 * grants, Zod forms, runTenantAction server actions and server-rendered pages.
 *
 * TypeScript output is formatted with Prettier afterwards, so these templates
 * only need to be valid code; SQL is written as it should appear.
 */
import { TEXT_MAX, titleField, type Field } from './fields.ts';
import type { ModuleNames } from './names.ts';

export interface ModuleSpec {
  names: ModuleNames;
  fields: Field[];
  /** Migration version, YYYYMMDDHHMMSS. */
  timestamp: string;
}

export type Permission = 'view' | 'create' | 'edit' | 'delete';

/** Default roles per permission (owners hold every permission anyway). */
export const DEFAULT_ROLES: Record<Permission, string[]> = {
  view: ['manager', 'front_desk', 'sales', 'viewer'],
  create: ['manager', 'front_desk', 'sales'],
  edit: ['manager', 'front_desk', 'sales'],
  delete: ['manager'],
};

const PERMISSIONS: Permission[] = ['view', 'create', 'edit', 'delete'];

interface View {
  n: ModuleNames;
  fields: Field[];
  title: Field;
  hasMoney: boolean;
  /** Permission key, e.g. ci_widgets.view */
  key: (p: Permission) => string;
  /** Exported identifiers. */
  id: {
    perms: string;
    type: string;
    input: string;
    query: string;
    schema: string;
    columns: string;
    list: string;
    get: string;
    create: string;
    update: string;
    remove: string;
    notices: string;
    errors: string;
    errorType: string;
    formError: string;
    errorCode: string;
    nav: string;
    listPage: string;
    newPage: string;
    detailPage: string;
    fieldsComponent: string;
    idField: string;
    row: string;
  };
}

function view(spec: ModuleSpec): View {
  const { names: n, fields } = spec;
  const S = n.singularPascal;
  const s = n.singularCamel;
  return {
    n,
    fields,
    title: titleField(fields),
    hasMoney: fields.some((f) => f.type === 'money'),
    key: (p) => `${n.snake}.${p}`,
    id: {
      perms: `${n.singularConst}_PERMISSIONS`,
      type: S,
      input: `${S}Input`,
      query: `${S}Query`,
      schema: `${s}FormSchema`,
      columns: `${s}Columns`,
      list: `list${n.pascal}`,
      get: `get${S}`,
      create: `create${S}`,
      update: `update${S}`,
      remove: `delete${S}`,
      notices: `${n.singularConst}_NOTICES`,
      errors: `${n.singularConst}_ERRORS`,
      errorType: `${S}ErrorCode`,
      formError: `${s}FormError`,
      errorCode: `${s}ErrorCode`,
      nav: `${n.camel}Nav`,
      listPage: `${n.pascal}Page`,
      newPage: `New${S}Page`,
      detailPage: `${S}DetailPage`,
      fieldsComponent: `${S}Fields`,
      idField: `${s}Id`,
      row: s,
    },
  };
}

const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lowerLabel = (f: Field) => f.label.toLowerCase();

