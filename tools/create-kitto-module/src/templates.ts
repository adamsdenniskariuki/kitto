function fieldJsx(v: View, f: Field): string {
  const row = v.id.row;
  const value = `${row}?.${f.column}`;
  const common = `label=${JSON.stringify(f.label)} name="${f.name}"${f.required ? ' required' : ''}`;
  switch (f.type) {
    case 'text':
      return `<TextField ${common} maxLength={${TEXT_MAX.text}} autoComplete="off" defaultValue={${value}${f.required ? '' : " ?? ''"}} />`;
    case 'longtext':
      return `<TextareaField ${common} rows={3} maxLength={${TEXT_MAX.longtext}} defaultValue={${value}${f.required ? '' : " ?? ''"}} />`;
    case 'int':
      return `<TextField ${common} type="number" step={1} inputMode="numeric" autoComplete="off" defaultValue={${value}${f.required ? '' : " ?? ''"}} />`;
    case 'numeric':
      return `<TextField ${common} inputMode="decimal" pattern={DECIMAL_PATTERN} autoComplete="off" hint="e.g. 12.5" defaultValue={${value}${f.required ? '' : " ?? ''"}} />`;
    case 'money':
      return `<TextField label={\`${f.label} (\${currency})\`} name="${f.name}"${f.required ? ' required' : ''} inputMode="decimal" pattern={MONEY_PATTERN} autoComplete="off" hint="e.g. 4500 or 4500.50" defaultValue={amount(${value}, currency)} />`;
    case 'bool':
      return `<Checkbox label=${JSON.stringify(f.label)} name="${f.name}" value="true" defaultChecked={${value}} />`;
    case 'date':
      return `<TextField ${common} type="date" defaultValue={${value}${f.required ? '' : " ?? ''"}} />`;
  }
}

function cellJsx(f: Field): string {
  const value = `r.${f.column}`;
  const maybe = (expr: string) => (f.required ? expr : `${value} === null ? '' : ${expr}`);
  switch (f.type) {
    case 'text':
    case 'longtext':
      return value;
    case 'int':
    case 'numeric':
      return maybe(`formatNumber(${value}, ctx.tenant)`);
    case 'money':
      return f.required
        ? `<Money minor={${value}} tenant={ctx.tenant} />`
        : `${value} === null ? '' : <Money minor={${value}} tenant={ctx.tenant} />`;
    case 'bool':
      return `${value} ? 'Yes' : 'No'`;
    case 'date':
      return maybe(`formatDay(${value}, ctx.tenant.locale)`);
  }
}

